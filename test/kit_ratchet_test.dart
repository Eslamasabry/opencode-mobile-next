Map<String, int> _countG1(String code) {
  final counts = <String, int>{};
  for (final entry in _g1Regexes.entries) {
    final n = entry.value.allMatches(code).length;
    if (n > 0) counts[entry.key] = n;
  }
  return counts;
}

