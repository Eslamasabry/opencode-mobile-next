bool _isGenerated(String path) {
  if (path.startsWith('lib/l10n/app_localizations') && path.endsWith('.dart')) {
    return true;
  }
  return path.endsWith('.g.dart') || path.endsWith('.freezed.dart');
}

/// Strips full-line `//` (and `///`) comments, same technique as
/// test/design_standard_test.dart's `_code`, so doc comments never count.
String _stripLineComments(String source) => source
    .split('\n')
    .where((line) => !line.trimLeft().startsWith('//'))
    .join('\n');

String _codeOf(String path) =>
    _stripLineComments(File(path).readAsStringSync());

/// Recursively lists .dart files under [root] (a path relative to the repo
/// root, e.g. 'lib' or 'lib/ui'), as sorted repo-relative POSIX paths,
/// excluding lib/ui/kit/** and generated files.
List<String> _dartFiles(String root) {
  final dir = Directory(root);
  if (!dir.existsSync()) return const [];
  final files =
      dir
          .listSync(recursive: true)
          .whereType<File>()
          .map((f) => f.path.replaceAll(Platform.pathSeparator, '/'))
          .where((p) => p.endsWith('.dart'))
          .where((p) => !p.startsWith('lib/ui/kit/'))
          .where((p) => !_isGenerated(p))
          .toList()
        ..sort();
  return files;
}

