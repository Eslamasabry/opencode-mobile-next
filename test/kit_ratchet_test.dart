Map<String, dynamic> _loadBaseline() {
  final file = File('test/kit_ratchet_baseline.json');
  if (!file.existsSync()) return {};
  return jsonDecode(file.readAsStringSync()) as Map<String, dynamic>;
}

/// Sorts a gate's file -> pattern -> count map, dropping zero entries and
/// empty files, for stable JSON output.
Map<String, Map<String, int>> _sorted(Map<String, Map<String, int>> gate) {
  final files = gate.keys.where((f) => gate[f]!.isNotEmpty).toList()..sort();
  return {
    for (final f in files)
      f: {for (final p in (gate[f]!.keys.toList()..sort())) p: gate[f]![p]!},
  };
}

/// Prints [gate]'s dropped entries and the command that commits them. A
/// passing run with nothing dropped prints nothing.
void _printDrops(
  String gate,
  Map<String, Map<String, int>> current,
  Map<String, dynamic> baseline,
) {
  final drops = _drops(current, baseline);
  if (drops.isEmpty) return;
  stdout.writeln(
    '$gate: ${drops.length} baseline entries dropped — commit the '
    'smaller numbers with KIT_RATCHET_WRITE=1 KIT_RATCHET_GATES=$gate:\n'
    '  ${drops.join('\n  ')}',
  );
}

