package io.github.eslamasabry.oc.tools.strings

import java.nio.file.Files
import java.nio.file.Path
import kotlin.io.path.createDirectories
import kotlin.io.path.deleteIfExists
import kotlin.io.path.isDirectory
import kotlin.io.path.listDirectoryEntries
import kotlin.io.path.name
import kotlin.io.path.readText
import kotlin.io.path.writeText

object XmlWriter {
    private val formatToken = Regex("""%\d+\$[ds]""")

    /** `en` → `values`, `ar` → `values-ar`, `pt_BR` → `values-pt-rBR` (CMP/Android qualifier syntax). */
    fun folder(locale: String, template: String): String {
        if (locale == template) return "values"
        val parts = locale.split('_', '-')
        return when (parts.size) {
            1 -> "values-${parts[0]}"
            2 -> if (parts[1].length == 2) "values-${parts[0]}-r${parts[1].uppercase()}" else error("Unsupported locale $locale")
            else -> error("Unsupported locale $locale")
        }
    }

    fun profileFor(feature: String) = if (feature == "os") XmlText.Profile.ANDROID else XmlText.Profile.CMP

    fun render(resources: List<Resource>, feature: String, sourceName: String, nativeOnly: List<String> = emptyList()): String {
        val profile = profileFor(feature)
        val sb = StringBuilder()
        sb.append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n")
        sb.append("<!-- Converted once from $sourceName by native/tools/strings (plan 06 §13.3).\n")
        sb.append("     The ARB files are frozen with Flutter: edit this file, not the ARB. -->\n")
        sb.append("<resources>\n")
        for (r in resources) when (r) {
            is Resource.Str -> {
                val attrs = if (profile == XmlText.Profile.ANDROID && '%' in r.text && !formatToken.containsMatchIn(r.text)) {
                    " formatted=\"false\""
                } else ""
                sb.append("    <string name=\"${r.name}\"$attrs>${XmlText.escape(r.text, profile)}</string>\n")
            }
            is Resource.Plurals -> {
                sb.append("    <plurals name=\"${r.name}\">\n")
                for ((q, text) in r.items) sb.append("        <item quantity=\"$q\">${XmlText.escape(text, profile)}</item>\n")
                sb.append("    </plurals>\n")
            }
        }
        if (nativeOnly.isNotEmpty()) {
            sb.append("    <!-- Not from the ARB files: copy added in :ui:words after the conversion (kept by every rerun). -->\n")
            for (raw in nativeOnly) sb.append("    ").append(raw).append('\n')
        }
        sb.append("</resources>\n")
        return sb.toString()
    }

    /**
     * `strings_os.xml` for Android `res` (plan 06 §13.2): the same names and text as the CMP copy, written for
     * aapt2. Quotes, a leading `@`/`?` and significant spaces become `\uXXXX`; in a string with arguments a literal
     * `%` becomes `%%`; a string with a `%` and no arguments gets `formatted="false"`.
     */
    fun renderAndroidRes(resources: List<Resource>, sourceName: String): String {
        val sb = StringBuilder()
        sb.append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n")
        sb.append("<!-- Generated by native/tools/strings from $sourceName (plan 06 §13.2). Do not edit: change\n")
        sb.append("     composeResources/values*/strings_os.xml and rerun `strings convert`; `strings check` compares the two. -->\n")
        sb.append("<resources>\n")
        fun value(t: String, args: Boolean) = XmlText.escape(AndroidStrings.encodePercent(t, args), XmlText.Profile.ANDROID)
        for (r in resources) when (r) {
            is Resource.Str -> {
                val attrs = if ('%' in r.text && !formatToken.containsMatchIn(r.text)) " formatted=\"false\"" else ""
                sb.append("    <string name=\"${r.name}\"$attrs>${value(r.text, formatToken.containsMatchIn(r.text))}</string>\n")
            }
            is Resource.Plurals -> {
                // getQuantityString formats every item when it is given arguments, so one item's tokens decide.
                val args = r.items.values.any { formatToken.containsMatchIn(it) }
                val plain = !args && r.items.values.any { '%' in it }
                sb.append("    <plurals name=\"${r.name}\"${if (plain) " formatted=\"false\"" else ""}>\n")
                for ((q, text) in r.items) sb.append("        <item quantity=\"$q\">${value(text, args)}</item>\n")
                sb.append("    </plurals>\n")
            }
        }
        sb.append("</resources>\n")
        return sb.toString()
    }

    private val element = Regex("""(?s)<(string|plurals)\s+name="([^"]+)"[^>]*?(?:/>|>.*?</\1>)""")

    /** `<string>`/`<plurals>` elements of [text] whose name [fromArb] does not claim, as raw XML. */
    fun nativeOnly(text: String, fromArb: (String) -> Boolean): List<String> =
        element.findAll(text).filter { !fromArb(it.groupValues[2]) }.map { it.value }.toList()

    /** Resource names of every `<string>`/`<plurals>` element in [text]. */
    fun names(text: String): List<String> = element.findAll(text).map { it.groupValues[2] }.toList()

    /**
     * Writes `values[-xx]/strings_<feature>.xml` under [out] and the unused group as `values[-xx]/strings_unused.xml`
     * under [unusedOut] (outside composeResources, so it never ships), and `strings_os.xml` into [androidResOut].
     *
     * Elements already in [out] whose names [fromArb] does not claim (copy added in `:ui:words` after the
     * conversion) are kept, in the file they were in. By default a name is claimed when this conversion produces it,
     * or it is a key the converter refused.
     */
    fun write(
        conversion: Conversion,
        out: Path,
        unusedOut: Path?,
        androidResOut: Path? = null,
        fromArb: (String) -> Boolean = defaultClaim(conversion),
    ) {
        val kept = HashMap<Pair<String, String>, MutableList<String>>() // (folder, file) → raw elements
        if (out.isDirectory()) for (dir in out.listDirectoryEntries("values*").filter { it.isDirectory() }) {
            for (f in dir.listDirectoryEntries("strings_*.xml")) {
                val raw = nativeOnly(f.readText(), fromArb)
                if (raw.isNotEmpty()) kept.getOrPut(dir.name to f.name) { mutableListOf() } += raw
            }
        }
        clean(out, "strings_*.xml"); unusedOut?.let { clean(it, "strings_*.xml") }; androidResOut?.let { clean(it, "strings_os.xml") }
        val written = HashSet<Pair<String, String>>()
        for (loc in conversion.locales) {
            val folder = folder(loc.locale, conversion.template)
            val features = loc.files.keys + (if (conversion.nativeOs[loc.locale].isNullOrEmpty()) emptySet() else setOf(Conversion.OS))
            for (feature in features.toSortedSet()) {
                val resources = if (feature == Conversion.OS) conversion.osResources(loc.locale) else loc.files.getValue(feature)
                if (resources.isEmpty()) continue
                val source = "lib/l10n/app_${loc.locale}.arb" +
                    if (feature == Conversion.OS && !conversion.nativeOs[loc.locale].isNullOrEmpty()) " and android/app/src/main/res/$folder" else ""
                if (feature == LocaleResult.UNUSED) {
                    val root = unusedOut ?: continue
                    root.resolve(folder).createDirectories().resolve("strings_unused.xml").writeText(render(resources, feature, source))
                    continue
                }
                val file = "strings_$feature.xml"
                out.resolve(folder).createDirectories().resolve(file)
                    .writeText(render(resources, feature, source, kept[folder to file].orEmpty()))
                written += folder to file
                if (feature == Conversion.OS && androidResOut != null) {
                    androidResOut.resolve(folder).createDirectories().resolve(file).writeText(renderAndroidRes(resources, source))
                }
            }
        }
        for ((where, raw) in kept) if (where !in written) {
            val (folder, file) = where
            out.resolve(folder).createDirectories().resolve(file).writeText(render(emptyList(), "", "no ARB file", raw))
        }
    }

    fun defaultClaim(c: Conversion): (String) -> Boolean {
        val names = HashSet<String>()
        for (l in c.locales) for (r in l.files.values.flatten()) { names += r.name; names += r.key }
        c.nativeOs.values.flatten().forEach { names += it.name }
        c.problems.forEach { names += it.key }
        return { it in names }
    }

    private fun clean(root: Path, glob: String) {
        if (!root.isDirectory()) return
        for (dir in root.listDirectoryEntries("values*").filter { it.isDirectory() }) {
            dir.listDirectoryEntries(glob).forEach { it.deleteIfExists() }
            if (dir.listDirectoryEntries().isEmpty()) Files.delete(dir)
        }
    }
}

object ReportWriter {
    private fun StringBuilder.hand(e: Expansion, c: Conversion) {
        val messages = e.converted.sumOf { it.locales.size }
        appendLine("## Hand-converted (${e.converted.size} keys, $messages messages)")
        appendLine()
        appendLine("CMP XML cannot hold these as one resource. Each key has a reviewed recipe in `hand-recipes.tsv`, applied to")
        appendLine("every language before conversion, so plural categories, `__eqN` strings, escaping and argument numbering are the")
        appendLine("converter's. `HandWords.kt` (generated into `:ui:words`) is the code half:")
        appendLine()
        appendLine("- **select** → one string `<key>__<branch>` per branch of any language (the text around the select copied in; a")
        appendLine("  language without a branch reads its own `other`, as ICU does). `HandWords.<key>(value)` picks the string with a")
        appendLine("  `when`; any other value reads `other`. The select argument is no longer a format argument.")
        appendLine("- **split-plurals** → `<key>` keeps the sentence with `%N\$s` where each plural was, and every plural becomes")
        appendLine("  `<plurals name=\"<key>__<count>\">` (+ its `__eqN`). `HandWords.<key>(…)` / `<key>Text(…)` fill the sentence.")
        appendLine("  ICU meaning is kept exactly: the sentence never varied with the counts, only the pieces did. A language that")
        appendLine("  writes a count as a plain number keeps `%N\$d` in its sentence and has no piece.")
        appendLine()
        appendLine("| key | recipe | languages | resources | why / note |")
        appendLine("|---|---|---|---|---|")
        for (h in e.converted) {
            val res = h.names.flatMap { n -> listOf(n) + (c.plans[n]?.exact.orEmpty().map { "${n}__eq$it" }) }
            appendLine("| `${h.key}` | ${h.recipe.kind.id} | ${h.locales.joinToString(", ")} | ${res.joinToString(" ") { "`$it`" }} | ${h.recipe.note} |")
        }
        appendLine()
        appendLine("Each message, as it was and what it became (template placeholder order shown as `%N`):")
        appendLine()
        for (h in e.converted) {
            appendLine("### `${h.key}` (${h.recipe.kind.id})")
            appendLine()
            val placeholders = h.names.mapNotNull { n -> c.plans[n]?.let { p -> "`$n`(" + p.placeholders.joinToString(", ") { "%${it.index}=${it.name}" } + ")" } }
            appendLine("Arguments: " + placeholders.joinToString("; "))
            appendLine()
            for (locale in h.locales) {
                val src = h.sources[locale].orEmpty().replace("\n", "⏎").replace("|", "\\|")
                appendLine("- **$locale**: `$src`")
                val loc = c.locales.firstOrNull { it.locale == locale } ?: continue
                val made = loc.files.values.flatten().filter { e.baseKey(it.key) == h.key && it.name in h.names }
                for (r in made) when (r) {
                    is Resource.Str -> appendLine("  - `${r.name}` = `${r.text.replace("\n", "⏎").replace("|", "\\|")}`")
                    is Resource.Plurals -> appendLine("  - `${r.name}` = " + r.items.entries.joinToString(" · ") { "${it.key}: `${it.value.replace("\n", "⏎").replace("|", "\\|")}`" })
                }
                val unref = e.unreferencedPieces[locale].orEmpty().filter { it.startsWith(h.key + "__") }
                if (unref.isNotEmpty()) appendLine("  - no ${unref.joinToString { "`$it`" }}: this language writes the count as a number")
            }
            appendLine()
        }
    }

    private fun StringBuilder.native(c: Conversion) {
        appendLine("## Android native strings merged into strings_os (plan 06 §13.3 step 7)")
        appendLine()
        appendLine("From `android/app/src/main/res/values*/` (strings.xml, widget_v2_strings.xml, widget_v2_bridge_strings.xml,")
        appendLine("scheduled_prompts.xml, bb_idle_strings.xml). Names kept, because pinned shortcuts and widgets reference them. Read")
        appendLine("with aapt2's rules; `%%` became `%` and a non-positional `%d`/`%s` became `%1\$d`/`%1\$s` (same output). The")
        appendLine("Android res copy in `:ui:words` `android-res/` writes them back for aapt2.")
        appendLine()
        appendLine("| lang | strings | plurals |")
        appendLine("|---|---:|---:|")
        for ((locale, res) in c.nativeOs) appendLine("| $locale | ${res.count { it is Resource.Str }} | ${res.count { it is Resource.Plurals }} |")
        appendLine()
        val en = c.nativeOs[c.template].orEmpty().map { it.name }
        for ((locale, res) in c.nativeOs) {
            if (locale == c.template) continue
            val missing = en - res.map { it.name }.toSet()
            appendLine("- $locale lacks ${missing.size} of the ${en.size} native names" + if (missing.isEmpty()) "." else ": " + missing.joinToString(", ") { "`$it`" })
        }
        appendLine()
    }

    fun write(conversion: Conversion, routing: Routing?, dir: Path, skippedProblems: Boolean, expansion: Expansion? = null) {
        dir.createDirectories()
        dir.listDirectoryEntries().filter { !it.isDirectory() }.forEach { it.deleteIfExists() }
        dir.resolve("convert-report.md").writeText(markdown(conversion, routing, skippedProblems, expansion))
        for (loc in conversion.locales) {
            if (loc.missing.isNotEmpty()) dir.resolve("missing-${loc.locale}.txt").writeText(loc.missing.joinToString("\n", postfix = "\n"))
            if (loc.unreachableBranches.isNotEmpty()) {
                dir.resolve("unreachable-${loc.locale}.txt").writeText(loc.unreachableBranches.joinToString("\n", postfix = "\n"))
            }
            if (loc.orphans.isNotEmpty()) dir.resolve("orphans-${loc.locale}.txt").writeText(loc.orphans.joinToString("\n", postfix = "\n"))
        }
        dir.resolve("unsupported.tsv").writeText(
            "locale\tkey\tkind\tdetail\n" +
                conversion.problems.joinToString("") { "${it.locale}\t${it.key}\t${it.kind}\t${it.detail.replace('\t', ' ').replace('\n', ' ')}\n" },
        )
        dir.resolve("placeholders.tsv").writeText(
            "key\tplural_arg\targs (index:name:type:format)\n" +
                conversion.plans.values.filter { it.placeholders.isNotEmpty() }.joinToString("") { p ->
                    "${p.key}\t${p.pluralArg ?: ""}\t" +
                        p.placeholders.joinToString(" ") { "${it.index}:${it.name}:${it.type ?: "-"}:${it.format ?: "-"}" } + "\n"
                },
        )
        dir.resolve("exact-selectors.tsv").writeText(
            "key\tN (each has <key>__eqN in every language that has the key)\n" +
                conversion.plans.values.filter { it.exact.isNotEmpty() }.joinToString("") { "${it.key}\t${it.exact.joinToString(",")}\n" },
        )
        if (routing != null) {
            dir.resolve("key-routes.tsv").writeText(
                "key\tfeature\treaders\tfirst reader\n" +
                    conversion.plans.values.joinToString("") { p ->
                        val readers = routing.usage[p.key].orEmpty()
                        "${p.key}\t${p.feature ?: LocaleResult.UNUSED}\t${readers.size}\t${readers.firstOrNull() ?: ""}\n"
                    },
            )
        }
    }

    fun markdown(c: Conversion, routing: Routing?, skippedProblems: Boolean, expansion: Expansion? = null): String = buildString {
        val en = c[c.template]
        val base = { k: String -> expansion?.baseKey(k) ?: k }
        appendLine("# ARB → CMP conversion report")
        appendLine()
        appendLine("Generated by `native/tools/strings` (`strings convert`). Template: `${c.template}`.")
        appendLine("Keys are counted as ARB keys: a hand-converted key counts once, however many resources it became.")
        if (skippedProblems) appendLine("Run with `--skip-unsupported`: the ${c.problems.size} messages below were NOT converted.")
        appendLine()
        appendLine("## Keys per language")
        appendLine()
        appendLine("`in = converted + unused + not convertible + orphans` must hold for every row.")
        appendLine()
        appendLine("| lang | in (ARB) | converted | unused | not convertible | orphans dropped | in = out | missing vs ${c.template} | `<string>` | `<plurals>` | `__eqN` | promoted to plurals |")
        appendLine("|---|---:|---:|---:|---:|---:|:---:|---:|---:|---:|---:|---:|")
        for (l in c.locales) {
            val keysIn = l.keysInBase(base)
            val conv = l.convertedKeys(includeUnused = false).map(base).toSet().size
            val unused = l.files[LocaleResult.UNUSED].orEmpty().map { base(it.key) }.toSet().size
            val skipped = l.skipped.map(base).toSet().size
            val sum = conv + unused + skipped + l.orphans.size
            val all = l.files.values.flatten()
            val eq = all.count { it is Resource.Str && it.name != it.key }
            val plurals = all.count { it is Resource.Plurals }
            val strings = all.count { it is Resource.Str } - eq
            appendLine(
                "| ${l.locale} | $keysIn | $conv | $unused | $skipped | ${l.orphans.size} | " +
                    "${if (sum == keysIn) "yes" else "**NO ($sum)**"} | ${l.missing.map(base).toSet().size} | $strings | $plurals | $eq | ${l.promoted.size} |",
            )
        }
        appendLine()
        appendLine("Missing keys fall back to `values/` at runtime. Lists: `missing-<lang>.txt`; dropped orphans: `orphans-<lang>.txt`.")
        appendLine()

        val features = c.locales.flatMap { it.files.keys }.toSortedSet()
        appendLine("## Keys per feature file")
        appendLine()
        appendLine("| file | " + c.locales.joinToString(" | ") { it.locale } + " |")
        appendLine("|---|" + c.locales.joinToString("") { "---:|" })
        for (f in features) {
            val name = if (f == LocaleResult.UNUSED) "strings_unused.xml (not shipped)" else "strings_$f.xml"
            appendLine("| $name | " + c.locales.joinToString(" | ") { l -> l.files[f].orEmpty().map { base(it.key) }.toSet().size.toString() } + " |")
        }
        appendLine()

        if (routing != null) {
            appendLine("## Routing")
            appendLine()
            val byPrefix = c.plans.values.count { p -> routing.usage[p.key].isNullOrEmpty() && p.feature != null }
            appendLine("- Template keys: ${en.keysInBase(base)}. Read by Dart code: ${routing.usage.size}. Routed by key prefix only: $byPrefix.")
            appendLine("- Unused (read by no Dart file): ${routing.unused.size}, written to `strings_unused.xml` outside composeResources for the owner to confirm.")
            appendLine("- Per-key routes and readers: `key-routes.tsv`.")
            appendLine()
        }

        if (expansion != null && expansion.converted.isNotEmpty()) hand(expansion, c)
        if (c.nativeOs.isNotEmpty()) native(c)
        val unusedKeys = en.files[LocaleResult.UNUSED].orEmpty().map { base(it.key) }.distinct()
        appendLine("## Unused keys (${unusedKeys.size})")
        appendLine()
        appendLine("Read by no Dart file and matched by no key prefix. Not shipped: written to")
        appendLine("`native/tools/strings/unused/values*/strings_unused.xml`, outside composeResources, for the owner to confirm")
        appendLine("before the ARB freeze (delete them there, or move one into a `strings_<feature>.xml` when a screen needs it).")
        appendLine()
        for (k in unusedKeys) appendLine("- `$k`")
        appendLine()

        appendLine("## Not convertible (${c.problems.size} messages)")
        appendLine()
        if (c.problems.isEmpty()) appendLine("None.")
        for ((kind, ps) in c.problems.groupBy { it.kind }) {
            appendLine("### ${kind.name}: ${kind.label} (${ps.size})")
            appendLine()
            for ((key, kps) in ps.groupBy { it.key }) {
                val own = kps.firstOrNull { it.detail != "template message is not convertible" } ?: kps.first()
                appendLine("- `$key` [${kps.joinToString(",") { it.locale }}]: ${own.detail.take(160)}")
            }
            appendLine()
        }

        val decimal = c.plans.values.filter { p -> p.placeholders.any { it.format != null } }
        appendLine("## Formatted numbers (${decimal.size} keys)")
        appendLine()
        appendLine("These placeholders had an ARB `format` (e.g. `decimalPattern`) and became `%N\$s`: call sites must pass a")
        appendLine("number already formatted for the locale. Keys: " + decimal.joinToString(", ") { "`${it.key}`" })
        appendLine()
        appendLine("## Exact plural selectors")
        appendLine()
        appendLine("${c.plans.values.count { it.exact.isNotEmpty() }} keys use `=N`; each gets `<key>__eqN` in every language (`exact-selectors.tsv`).")
        appendLine()
        val unreachable = c.locales.filter { it.unreachableBranches.isNotEmpty() }
        if (unreachable.isNotEmpty()) {
            appendLine("## Plural branches no rule can select (dropped)")
            appendLine()
            appendLine("ICU branches for a category the language does not have (for example `one` in zh). ICU never picks them")
            appendLine("either, so nothing changes on screen. Lists: `unreachable-<lang>.txt`.")
            appendLine()
            for (l in unreachable) appendLine("- ${l.locale}: ${l.unreachableBranches.size}")
            appendLine()
        }
    }
}
