package io.github.eslamasabry.oc.ui.design.type

/** The ten type roles (Dart `KitTextRole`, `lib/ui/kit/kit_text.dart`). */
public enum class TypeRole { LargeTitle, Title, Headline, Body, RowTitle, Secondary, Label, Caption, Button, Mono }

/** Text tones (LOOK-14: always opaque; disabled text uses Tertiary). */
public enum class TextTone { Primary, Secondary, Tertiary, Accent, OnAccent, Attention, Success }

/** Font family of a role: Geist (sans) or Geist Mono. */
public enum class TypeFamily { Sans, Mono }
