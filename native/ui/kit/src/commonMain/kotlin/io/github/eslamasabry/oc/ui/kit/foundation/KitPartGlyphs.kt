/**
 * The few marks the part-B controls draw themselves (check, close, chevrons, more, reveal, warning). They are
 * kit-internal stand-ins until `KitGlyphs` (generated by `tools/glyphs/extract.py`, plan 06 §4.11) lands; each name
 * here maps one-to-one onto a Dart `AppIcons` glyph, so the swap is mechanical.
 */
internal object KitPartGlyphs {
    val Check: ImageVector = stroke("check") { moveTo(5f, 12.5f); lineTo(10f, 17.5f); lineTo(19f, 7f) }
    val Close: ImageVector = stroke("close") { moveTo(6f, 6f); lineTo(18f, 18f); moveTo(18f, 6f); lineTo(6f, 18f) }
    val ChevronDown: ImageVector = stroke("chevron-down") { moveTo(6f, 9f); lineTo(12f, 15f); lineTo(18f, 9f) }
    val ChevronUp: ImageVector = stroke("chevron-up") { moveTo(6f, 15f); lineTo(12f, 9f); lineTo(18f, 15f) }

    /** Points to the end; mirrored in RTL by [KitGlyph]. */
    val ChevronEnd: ImageVector = stroke("chevron-end") { moveTo(9f, 6f); lineTo(15f, 12f); lineTo(9f, 18f) }
    val More: ImageVector =
        stroke("more", width = 3f) {
            moveTo(5f, 12f); lineTo(5.01f, 12f); moveTo(12f, 12f); lineTo(12.01f, 12f); moveTo(19f, 12f); lineTo(19.01f, 12f)
        }
    val Eye: ImageVector =
        stroke("eye") {
            moveTo(2f, 12f); curveTo(5f, 6f, 19f, 6f, 22f, 12f); curveTo(19f, 18f, 5f, 18f, 2f, 12f); close()
            moveTo(15f, 12f); arcToRelative(3f, 3f, 0f, true, true, -6f, 0f); arcToRelative(3f, 3f, 0f, true, true, 6f, 0f)
        }
    val EyeOff: ImageVector =
        stroke("eye-off") {
            moveTo(2f, 12f); curveTo(5f, 6f, 19f, 6f, 22f, 12f); curveTo(19f, 18f, 5f, 18f, 2f, 12f); close()
            moveTo(4f, 4f); lineTo(20f, 20f)
        }
    val Warning: ImageVector =
        stroke("warning") {
            moveTo(12f, 3.5f); lineTo(22f, 20f); lineTo(2f, 20f); close(); moveTo(12f, 10f); lineTo(12f, 14f)
            moveTo(12f, 17f); lineTo(12f, 17.01f)
        }
    val Ring: ImageVector = stroke("ring") { moveTo(20f, 12f); arcToRelative(8f, 8f, 0f, true, true, -16f, 0f); arcToRelative(8f, 8f, 0f, true, true, 16f, 0f) }
    val Undo: ImageVector =
        stroke("undo") { moveTo(9f, 14f); lineTo(4f, 9f); lineTo(9f, 4f); moveTo(4f, 9f); lineTo(14f, 9f); curveTo(22f, 9f, 22f, 20f, 14f, 20f); lineTo(11f, 20f) }
    val Copy: ImageVector =
        stroke("copy") {
            moveTo(9f, 9f); lineTo(20f, 9f); lineTo(20f, 20f); lineTo(9f, 20f); close()
            moveTo(5f, 15f); lineTo(4f, 15f); lineTo(4f, 4f); lineTo(15f, 4f); lineTo(15f, 5f)
        }
    val Paste: ImageVector =
        stroke("paste") {
            moveTo(9f, 4f); lineTo(15f, 4f); lineTo(15f, 7f); lineTo(9f, 7f); close()
            moveTo(9f, 5.5f); lineTo(5f, 5.5f); lineTo(5f, 21f); lineTo(19f, 21f); lineTo(19f, 5.5f); lineTo(15f, 5.5f)
        }

    /** Glyphs that point along the reading direction and so mirror in RTL (B-KIT-001). */
    val directional: Set<ImageVector> = setOf(ChevronEnd, Undo)

    private fun stroke(name: String, width: Float = 2f, block: PathBuilder.() -> Unit): ImageVector =
        ImageVector.Builder(name = name, defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 24f, viewportHeight = 24f)
            .path(
                stroke = SolidColor(Color.Black),
                strokeLineWidth = width,
                strokeLineCap = StrokeCap.Round,
                strokeLineJoin = StrokeJoin.Round,
                pathBuilder = block,
            )
            .build()
}

/** Draws [glyph] decoratively (no content description: the owning control carries the words), tinted [tint]. */
@Composable
internal fun KitGlyph(glyph: ImageVector, tint: Color, size: Dp, modifier: Modifier = Modifier) {
    val mirror = glyph in KitPartGlyphs.directional && LocalLayoutDirection.current == LayoutDirection.Rtl
    Image(
        imageVector = glyph,
        contentDescription = null,
        colorFilter = ColorFilter.tint(tint),
        modifier = modifier.size(size).then(if (mirror) Modifier.scale(-1f, 1f) else Modifier),
    )
}
