package io.github.eslamasabry.oc.core.data.secret

import io.github.eslamasabry.oc.core.common.Outcome

/**
 * Passwords and tokens (plan 05 §4, ADR §9.8). Names keep today's shapes (`pw.<id>`, `oc.codexToken.<id>`, …); names
 * are ids, not secrets. Values never reach logs, `Failure.details` or `toString()`.
 *
 * Failures are `Failure.SecretUnavailable` (plan 05 §4.2: "enter the password again"). Never a plaintext fallback,
 * and never "" for a failure.
 */
public interface SecretStore {
    public suspend fun read(name: String): Outcome<String?>

    public suspend fun write(name: String, value: String): Outcome<Unit>

    public suspend fun delete(name: String): Outcome<Unit>

    /** Names starting with [prefix] ("reset saved sign-ins" enumerates orphans). */
    public suspend fun names(prefix: String): Outcome<Set<String>>
}

/**
 * The cipher seam (plan 05 §4.2 `KeystoreAead`): Android Keystore AES-256-GCM in production, a software AES-GCM in JVM
 * tests. The IV is generated by the implementation (Keystore refuses caller IVs by default).
 */
public interface Aead {
    /** Returns the 12-byte IV and `ciphertext ‖ tag[16]`. */
    public fun seal(plaintext: ByteArray, aad: ByteArray): Sealed

    /** Throws on a bad tag or any key problem. */
    public fun open(iv: ByteArray, ciphertextAndTag: ByteArray, aad: ByteArray): ByteArray

    public class Sealed(public val iv: ByteArray, public val ciphertextAndTag: ByteArray) {
        override fun toString(): String = "Sealed(iv=${iv.size}, body=${ciphertextAndTag.size})"
    }
}

/** The entry file seam: `shared_prefs/oc_secrets_v1.xml` on Android. Blocking; values are already-encrypted text. */
public interface SecretEntries {
    public fun get(name: String): String?

    public fun names(): Set<String>

    /** True only when the platform acknowledged the disk write. */
    public fun put(name: String, value: String): Boolean

    public fun remove(name: String): Boolean
}
