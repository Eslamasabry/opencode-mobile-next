#!/usr/bin/env python3
"""Generate the native design token values from the Flutter kit (the product's source of truth).

Reads, from the Flutter app at a git ref (default mobile-next/master, the 2.1.1 product):
  lib/ui/kit/kit_tokens.dart        KitTokens.fallback sizes, radii, spacing + the static constants
  lib/ui/kit/kit_text.dart          KitText.styleFor: the ten type roles
  lib/ui/kit/kit_motion.dart        durations, springs, laps
  lib/ui/theme_roles.dart           every `const x = ThemeRoles(...)` pack (Graphite and the rest)
  lib/ui/kit/style/kit_style*.dart  the style schools' declared constants and sharp radii
and writes one Kotlin file of values (FlutterKit*.kt objects). Native token files read these values; nothing in them
is typed by hand. Every number in the output comes from Flutter.

Usage: gen_tokens.py --repo /path/to/oc_app [--ref mobile-next/master] --out path/to/FlutterKit.kt [--report out.md]
"""
import argparse, os, re, subprocess, sys
from fractions import Fraction

def show(repo, ref, path):
    return subprocess.run(["git", "-C", repo, "show", f"{ref}:{path}"], capture_output=True, text=True, check=True).stdout

def snake(name):
    s = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name.lstrip("_"))
    return s.upper()

SYMBOLS = {}
COVER = set()


def num(expr):
    """Evaluate a Dart numeric literal or a simple expression (1 / 3.6, .5, 34 / 28, badgeHeight / 3)."""
    e = expr.strip().rstrip(",")
    e = re.sub(r"\b([a-zA-Z_]\w*)\b", lambda m: repr(SYMBOLS[m.group(1)]) if m.group(1) in SYMBOLS else m.group(1), e)
    if not re.fullmatch(r"[0-9.\s/*+\-()e]+", e):
        return None
    try:
        return float(eval(e, {"__builtins__": {}}, {}))
    except Exception:
        return None

def kfloat(v):
    return f"{v!r}f" if v != int(v) else f"{int(v)}f"

def kconst(v):
    """`Int = 16` for whole numbers (so native const vals can use them), `Float = 0.38f` otherwise."""
    return f"Int = {int(v)}" if v == int(v) else f"Float = {v!r}f"

def block(src, start_pat):
    """The text of the first balanced (...) after start_pat."""
    m = re.search(start_pat, src)
    if not m:
        return None
    i = src.index("(", m.end() - 1)
    depth = 0
    for j in range(i, len(src)):
        if src[j] == "(":
            depth += 1
        elif src[j] == ")":
            depth -= 1
            if depth == 0:
                return src[i + 1 : j]
    return None

def strip_comments(s):
    s = re.sub(r"//[^\n]*", "", s)
    return re.sub(r"/\*.*?\*/", "", s, flags=re.S)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True)
    ap.add_argument("--ref", default="mobile-next/master")
    ap.add_argument("--out", required=True)
    ap.add_argument("--report")
    ap.add_argument("--flutter-sdk", default="~/.shorebird/bin/cache/flutter/91f8bd75076e9c740aa13cf67eb9ec1a093f68f5/packages/flutter/lib/src/animation/curves.dart",
                    help="the pinned Flutter SDK's curves.dart; the named curves' numbers are read from it")
    a = ap.parse_args()
    sha = subprocess.run(["git", "-C", a.repo, "rev-parse", "--short=9", a.ref], capture_output=True, text=True, check=True).stdout.strip()
    get = lambda p: strip_comments(show(a.repo, a.ref, p))

    out = []
    w = out.append
    w(f"// GENERATED by native/tool/design/gen_tokens.py from the Flutter kit at {a.ref} ({sha}). Do not edit by hand:")
    w("// change the Flutter source or the generator, then run it again. Every value here is Flutter's.")
    w("@file:Suppress(\"unused\", \"MagicNumber\")")
    w("")
    w("package io.github.eslamasabry.oc.ui.design.generated")
    w("")
    w("import io.github.eslamasabry.oc.ui.design.color.Argb")
    w("import io.github.eslamasabry.oc.ui.design.color.Roles")
    w("import io.github.eslamasabry.oc.ui.design.color.argb")
    w("import io.github.eslamasabry.oc.ui.design.type.TypeFamily")
    w("import io.github.eslamasabry.oc.ui.design.type.TypeRole")
    w("import io.github.eslamasabry.oc.ui.design.type.TypeSpec")
    w("")

    # 1. KitTokens: the fallback's numeric fields and the class's static constants.
    tokens = get("lib/ui/kit/kit_tokens.dart")
    fb_start = tokens.index("factory KitTokens.fallback")
    fb = block(tokens[fb_start:], r"return KitTokens\(")
    fields = {}
    for name, val in re.findall(r"\b([a-zA-Z]\w*)\s*:\s*([-0-9.][0-9.\s/*]*)\s*,", fb):
        v = num(val)
        if v is not None:
            fields[name] = v
    m = re.search(r"handleSize:\s*const Size\(\s*([0-9.]+)\s*,\s*([0-9.]+)\s*\)", fb)
    if m:
        fields["handleWidth"], fields["handleThickness"] = float(m.group(1)), float(m.group(2))
    statics = {}
    for name, val in re.findall(r"static const (?:double|int) (\w+)\s*=\s*([^;]+);", tokens):
        v = num(val)
        if v is not None:
            statics[name] = v
    SYMBOLS.update(fields)
    SYMBOLS.update(statics)
    for _ in range(3):  # statics written as other statics (badgeOffset = badgeHeight / 3)
        for name, val in re.findall(r"static const (?:double|int) (\w+)\s*=\s*([^;]+);", tokens):
            v = num(val)
            if v is not None and name not in statics:
                statics[name] = v
                SYMBOLS[name] = v
    # constructor defaults (fieldCorner = fieldRadius, pillRadius = double.infinity)
    defaults = {}
    for name, val in re.findall(r"this\.(\w+)\s*=\s*([\w.]+)\s*,", tokens):
        if val == "double.infinity":
            defaults[name] = float("inf")
        else:
            v = num(val)
            if v is not None:
                defaults[name] = v
    SYMBOLS.update(defaults)
    # derived instance getters (leadColumn => iconTileSize + space3)
    derived = {}
    for name, val in re.findall(r"double get (\w+)\s*=>\s*([^;]+);", tokens):
        v = num(val)
        if v is not None:
            derived[name] = v
            SYMBOLS[name] = v
    w("/** `KitTokens.fallback` (lib/ui/kit/kit_tokens.dart): sizes, radii and spacing in logical pixels (dp). */")
    w("public object FlutterKitTokens {")
    for k in sorted(fields):
        w(f"    public const val {snake(k)}: {kconst(fields[k])}")
    w("")
    w("    // The class's static constants.")
    for k in sorted(statics):
        if k in fields:
            continue
        w(f"    public const val {snake(k)}: {kconst(statics[k])}")
    if defaults or derived:
        w("")
        w("    // Constructor defaults and derived getters (fieldCorner = fieldRadius, leadColumn = iconTileSize + space3).")
    for k in sorted(defaults):
        v = defaults[k]
        if v == float("inf"):
            w(f"    public const val {snake(k)}: Float = Float.POSITIVE_INFINITY")
        else:
            w(f"    public const val {snake(k)}: {kconst(v)}")
    for k in sorted(derived):
        w(f"    public const val {snake(k)}: {kconst(derived[k])}")
    # physical-pixel widths written as n / dpr (hairlineWidth, focusRingWidth)
    for name, n in re.findall(r"static double (\w+)\(BuildContext context\)\s*\{[^}]*?\b(\d+) / dpr", tokens, flags=re.S):
        w(f"    /** `KitTokens.{name}`: {n} physical px, in logical px: {n} / devicePixelRatio. */")
        w(f"    public const val {snake(name)}_PHYSICAL_PX: Int = {n}")
    # shadows (surfaceShadows, floatingShadows)
    for name in ("surfaceShadows", "floatingShadows"):
        m = re.search(rf"(?:List<BoxShadow> get {name}|List<BoxShadow> {name}\(BuildContext context\))(.*?)\];", tokens, flags=re.S)
        if not m:
            continue
        shadows, rest = [], m.group(1)
        while "BoxShadow(" in rest:
            body = block(rest, r"BoxShadow\(")
            shadows.append(body)
            rest = rest[rest.index(body) + len(body):]
        for i, sh in enumerate(shadows):
            blur = re.search(r"blurRadius:\s*(-?[0-9.]+)", sh); spread = re.search(r"spreadRadius:\s*(-?[0-9.]+)", sh)
            off = re.search(r"Offset\(\s*(-?[0-9.]+)\s*,\s*(-?[0-9.]+)\s*\)", sh); alpha = re.search(r"withValues\(alpha:\s*([0-9.]+)\)", sh)
            tag = snake(name) + ("" if i == 0 else f"_{i + 1}")
            w(f"    /** `{name}` shadow {i + 1}: colour `{re.search(r'color:\s*([^,]+)', sh).group(1).strip()}`. */")
            if blur: w(f"    public const val {tag}_BLUR: {kconst(float(blur.group(1)))}")
            if spread: w(f"    public const val {tag}_SPREAD: {kconst(float(spread.group(1)))}")
            if off:
                w(f"    public const val {tag}_DX: {kconst(float(off.group(1)))}")
                w(f"    public const val {tag}_DY: {kconst(float(off.group(2)))}")
            w(f"    public const val {tag}_ALPHA: {kconst(float(alpha.group(1)) if alpha else 1.0)}")
    w("}")
    w("")

    # 1b. The tokens that are colours or text styles of the theme's roles (KitTokens.fromRoles and the role getters).
    fr_start = tokens.index("factory KitTokens.fromRoles")
    fr = block(tokens[fr_start:], r"return KitTokens\(")
    def kt_role(expr, var):
        expr = expr.strip()
        m = re.fullmatch(rf"{var}\.isDark\s*\?\s*{var}\.(\w+)\s*:\s*{var}\.(\w+)", expr)
        if m:
            return f"if (r.dark) r.{m.group(1)} else r.{m.group(2)}"
        m = re.fullmatch(rf"{var}\.(\w+)", expr)
        return f"r.{m.group(1)}" if m else None
    colours = {}
    for name, expr in re.findall(r"(\w+):\s*(r\.[^,]+?|r\.isDark[^,]+?),\n", fr):
        k = kt_role(expr, "r")
        if k and name != "roles":
            colours[name] = k
    for name, expr in re.findall(r"Color get (\w+)\s*=>\s*([^;]+);", tokens):
        k = kt_role(expr, "roles")
        if k:
            colours[name] = k
    statics_roles = re.findall(r"static Color get (\w+)\s*=>\s*(graphite(?:Light|Dark))\.(\w+);", tokens)
    texts = re.findall(r"(\w+):\s*role\(KitTextRole\.(\w+),\s*r\.(\w+)\)", fr)
    lists = {}
    for name, body in re.findall(r"List<Color> get (\w+)\s*=>\s*\[(.*?)\];", tokens, flags=re.S):
        items = [kt_role(x, "roles") for x in body.split(",") if x.strip()]
        if all(items):
            lists[name] = items
    w("/** The tokens that are a role of the theme (`KitTokens.fromRoles` and its role getters): colour = role(roles). */")
    w("public object FlutterKitTokenRoles {")
    for k in sorted(colours):
        w(f"    public fun {k}(r: Roles): Argb = {colours[k]}")
    for k, items in sorted(lists.items()):
        w(f"    public fun {k}(r: Roles): List<Argb> = listOf({', '.join(items)})")
    for k, pack, role in statics_roles:
        w(f"    /** `KitTokens.{k}`: always {pack}.{role}, whatever the theme. */")
        w(f"    public val {k}: Argb get() = FlutterKitRoles.{pack}.{role}")
    w("}")
    w("")
    w("/** A text token: a type role drawn in a colour role (`KitTokens.fromRoles` `role(KitTextRole.x, r.y)`). */")
    w("public class FlutterTextToken(public val role: TypeRole, public val colour: (Roles) -> Argb)")
    w("")
    w("public object FlutterKitTokenText {")
    for name, role, col in texts:
        w(f"    public val {name}: FlutterTextToken = FlutterTextToken(TypeRole.{role[0].upper() + role[1:]}) {{ it.{col} }}")
    w("}")
    w("")
    COVER.update(set(fields) | set(statics) | set(defaults) | set(derived) | set(colours) | {k for k, _, _ in statics_roles} | {t[0] for t in texts} | set(lists)
                 | {"handleSize", "surfaceShadows", "floatingShadows", "hairlineWidth", "focusRingWidth"})

    # 2. Type: KitText.styleFor.
    text = get("lib/ui/kit/kit_text.dart")
    sf = text[text.index("static TextStyle styleFor(KitTextRole role)"):]
    sf = sf[: sf.index("};")]
    roles = {}
    for role, body in re.findall(r"KitTextRole\.(\w+)\s*=>\s*const TextStyle\((.*?)\)\s*,", sf, flags=re.S):
        size = num(re.search(r"fontSize:\s*([0-9.]+)", body).group(1))
        hm = re.search(r"height:\s*([0-9.]+)\s*/\s*([0-9.]+)", body)
        line = num(hm.group(1)) if hm else size
        wm = re.search(r"fontWeight:\s*FontWeight(?:\.w(\d+)|\((\d+)\))", body)
        weight = int(wm.group(1) or wm.group(2)) if wm else 400
        tm = re.search(r"letterSpacing:\s*(-?[0-9.]+)", body)
        track = float(tm.group(1)) if tm else 0.0
        mono = "AppMono" in body
        roles[role] = (int(size), int(line), weight, track, mono)
    w("/** `KitText.styleFor` (lib/ui/kit/kit_text.dart): size and line height in sp, weight, tracking in sp. */")
    w("public object FlutterKitType {")
    for role, (size, line, weight, track, mono) in roles.items():
        fam = ", TypeFamily.Mono" if mono else ""
        w(f"    public val {role[0].upper() + role[1:]}: TypeSpec = TypeSpec({size}, {line}, {weight}, {kfloat(track)}{fam})")
    w("}")
    w("")

    # 3. Motion.
    motion = get("lib/ui/kit/kit_motion.dart")
    w("/** `KitMotion` (lib/ui/kit/kit_motion.dart): durations in ms, springs (stiffness, damping per unit mass), laps. */")
    w("public object FlutterKitMotion {")
    durations = {}
    for name, ms in re.findall(r"static const (?:Duration )?(\w+)\s*=\s*Duration\(milliseconds:\s*(\d+)\)", motion):
        durations[name] = int(ms)
    for name, s in re.findall(r"static const (?:Duration )?(\w+)\s*=\s*Duration\(seconds:\s*(\d+)\)", motion):
        durations[name] = int(s) * 1000
    for k in sorted(durations):
        w(f"    public const val {snake(k)}_MS: Int = {durations[k]}")
    for name, body in re.findall(r"static const (\w+)\s*=\s*SpringDescription\((.*?)\);", motion, flags=re.S):
        st = re.search(r"stiffness:\s*([0-9.]+)", body); dp = re.search(r"damping:\s*([0-9.]+)", body); ms = re.search(r"mass:\s*([0-9.]+)", body)
        w(f"    public const val {snake(name)}_STIFFNESS: Float = {kfloat(float(st.group(1)))}")
        w(f"    public const val {snake(name)}_DAMPING: Float = {kfloat(float(dp.group(1)))}")
        w(f"    public const val {snake(name)}_MASS: Float = {kfloat(float(ms.group(1)) if ms else 1.0)}")
    for name, val in re.findall(r"static const double (\w+)\s*=\s*([^;]+);", motion):
        v = num(val)
        if v is not None:
            w(f"    public const val {snake(name)}: {kconst(v)}")
    w("}")
    w("")

    # 3b. Motion curves: KitMotion's `static const Curve` values, as the Flutter SDK defines each named curve
    # (packages/flutter/lib/src/animation/curves.dart). Native builds its easings from these numbers.
    w("/** A Flutter curve, as its SDK defines it: a cubic (x1, y1, x2, y2), a three-point cubic, or linear. */")
    w("public sealed class FlutterCurve {")
    w("    public data class Cubic(val x1: Float, val y1: Float, val x2: Float, val y2: Float) : FlutterCurve()")
    w("    /** `ThreePointCubic(a1, b1, midpoint, a2, b2)`: two cubics joined at [midX], [midY] (each point as x, y). */")
    w("    public data class ThreePointCubic(")
    w("        val a1x: Float, val a1y: Float, val b1x: Float, val b1y: Float, val midX: Float, val midY: Float,")
    w("        val a2x: Float, val a2y: Float, val b2x: Float, val b2y: Float,")
    w("    ) : FlutterCurve()")
    w("    /** `FlippedCurve(curve)`: `1 - curve(1 - t)`. */")
    w("    public data class Flipped(val curve: FlutterCurve) : FlutterCurve()")
    w("    public data object Linear : FlutterCurve()")
    w("}")
    w("")
    sdk = {
        "linear": "FlutterCurve.Linear",
        "easeInOutQuad": "FlutterCurve.Cubic(0.455f, 0.03f, 0.515f, 0.955f)",
        "easeOutQuad": "FlutterCurve.Cubic(0.25f, 0.46f, 0.45f, 0.94f)",
        "easeOutCubic": "FlutterCurve.Cubic(0.215f, 0.61f, 0.355f, 1.0f)",
        "easeInCubic": "FlutterCurve.Cubic(0.55f, 0.055f, 0.675f, 0.19f)",
        "easeInOutCubic": "FlutterCurve.Cubic(0.645f, 0.045f, 0.355f, 1.0f)",
        "easeOutBack": "FlutterCurve.Cubic(0.175f, 0.885f, 0.32f, 1.275f)",
        "easeInOut": "FlutterCurve.Cubic(0.42f, 0.0f, 0.58f, 1.0f)",
        "easeIn": "FlutterCurve.Cubic(0.42f, 0.0f, 1.0f, 1.0f)",
        "easeOut": "FlutterCurve.Cubic(0.0f, 0.0f, 0.58f, 1.0f)",
        "ease": "FlutterCurve.Cubic(0.25f, 0.1f, 0.25f, 1.0f)",
        "fastOutSlowIn": "FlutterCurve.Cubic(0.4f, 0.0f, 0.2f, 1.0f)",
        "easeInOutCubicEmphasized": "FlutterCurve.ThreePointCubic(0.05f, 0.0f, 0.133333f, 0.06f, 0.166666f, 0.4f, 0.208333f, 0.82f, 0.25f, 1.0f)",
    }
    sdk_src = os.path.expanduser(a.flutter_sdk) if a.flutter_sdk else None
    if sdk_src and os.path.exists(sdk_src):
        txt = open(sdk_src).read()
        for name, args in re.findall(r"static const Cubic (\w+)\s*=\s*Cubic\(([^)]*)\);", txt):
            v = [float(x) for x in args.split(",") if x.strip()]
            sdk[name] = "FlutterCurve.Cubic(" + ", ".join(kfloat(x) for x in v) + ")"
        for name, body in re.findall(r"static const ThreePointCubic (\w+)\s*=\s*ThreePointCubic\((.*?)\);", txt, flags=re.S):
            pts = [float(x) for x in re.findall(r"-?[0-9.]+", body)]
            sdk[name] = "FlutterCurve.ThreePointCubic(" + ", ".join(kfloat(x) for x in pts) + ")"
        w(f"// Curves read from the Flutter SDK's curves.dart ({sdk_src.split('/bin/cache/')[-1] if '/bin/cache/' in sdk_src else sdk_src}).")

    def curve_of(expr):
        expr = expr.strip()
        m = re.fullmatch(r"Curves\.(\w+)", expr)
        if m:
            return sdk.get(m.group(1))
        m = re.fullmatch(r"FlippedCurve\(\s*Curves\.(\w+)\s*,?\s*\)", expr, flags=re.S)
        if m and sdk.get(m.group(1)):
            return f"FlutterCurve.Flipped({sdk[m.group(1)]})"
        return None
    w("/** `KitMotion`'s curves (lib/ui/kit/kit_motion.dart). `emphasized` pairs with STANDARD_MS (kit_motion_parts.dart). */")
    w("public object FlutterKitCurves {")
    for name, expr in re.findall(r"static const Curve (\w+)\s*=\s*([^;]+);", motion, flags=re.S):
        c = curve_of(expr)
        if c:
            w(f"    public val {name}: FlutterCurve = {c}")
        else:
            w(f"    // {name} = {' '.join(expr.split())}: not a named SDK curve; not emitted")
    w("}")
    w("")

    # 4. Colour roles: every pack in theme_roles.dart.
    tr = get("lib/ui/theme_roles.dart")
    native_fields = ["ground","surface1","surface2","surface3","hairline","text1","text2","text3","accent","onAccent","partner","onPartner","attention","attentionFill","onAttentionFill","attentionSurface","attentionLine","success","scrim","codeKeyword","codeString","codeType","elevationShadow"]
    w("/** Every `const x = ThemeRoles(...)` in lib/ui/theme_roles.dart, role for role. */")
    w("public object FlutterKitRoles {")
    packs = {}
    for name in re.findall(r"const (\w+)\s*=\s*ThemeRoles\(", tr):
        body = block(tr, rf"const {name}\s*=\s*ThemeRoles\(")
        vals = dict(re.findall(r"(\w+):\s*Color\((0x[0-9A-Fa-f]{8})\)", body))
        dark = "Brightness.dark" in body
        missing = [f for f in native_fields if f not in vals]
        if missing:
            w(f"    // {name}: skipped, Flutter does not set {', '.join(missing)}")
            continue
        packs[name] = vals
        args = ", ".join(f"{f} = argb({vals[f].upper().replace('0X','0x')})" for f in native_fields)
        w(f"    public val {name}: Roles = Roles(dark = {str(dark).lower()}, {args})")
    w("}")
    w("")

    # 5. Style schools: declared constants and sharp radii.
    w("/** The style schools (lib/ui/kit/style/kit_style_*.dart): their declared constants and Corners=Sharp radius. */")
    w("public object FlutterKitStyles {")
    style_vals = {}
    for school in ["solid", "soft", "brutal", "paper", "signal"]:
        src = get(f"lib/ui/kit/style/kit_style_{school}.dart")
        sr = re.search(r"sharpRadius:\s*([0-9.]+)", src)
        style_vals[f"{school}_sharp_radius"] = float(sr.group(1)) if sr else 2.0
        for name, val in re.findall(r"static const (?:double )?(\w+)\s*=\s*([-0-9.][^;]*);", src):
            v = num(val)
            if v is not None:
                style_vals[f"{school}_{name.lstrip('_')}"] = v
    for k in sorted(style_vals):
        w(f"    public const val {snake(k)}: {kconst(style_vals[k])}")
    w("}")

    # coverage: every KitTokens member the Flutter UI reads is emitted, or is a method/the theme object
    refs = set()
    for path in subprocess.run(["git", "-C", a.repo, "ls-tree", "-r", "--name-only", a.ref, "lib/ui"], capture_output=True, text=True).stdout.split():
        if path.endswith(".dart"):
            body = show(a.repo, a.ref, path)
            refs |= set(re.findall(r"KitTokens\.([a-z]\w*)", body)) | set(re.findall(r"\btokens\.([a-z]\w*)", body))
    declared = set(re.findall(r"final [\w<>?]+ (\w+);", tokens)) | set(re.findall(r"\bget (\w+)\s*=>", tokens)) \
        | set(re.findall(r"static const (?:double|int|Color) (\w+)", tokens))
    methods = set(re.findall(r"(?:static )?[\w<>?]+ (\w+)\(", tokens)) | {"roles", "fallback", "fromRoles"}
    refs &= declared | methods
    missing = sorted(r for r in refs if r not in COVER and r not in methods)
    w("")
    w(f"// Coverage: {len(refs)} KitTokens members read by lib/ui; not emitted (methods, the roles object, or Flutter-only):")
    for i in range(0, len(missing), 8):
        w("//   " + ", ".join(missing[i:i + 8]))
    open(a.out, "w").write("\n".join(out) + "\n")
