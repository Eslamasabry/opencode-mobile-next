#!/usr/bin/env python3
"""Generate the native design token values from the Flutter kit (the product's source of truth).

Reads, from the Flutter app at a git ref (default mobile-next/master, the 2.1.1 product):
  lib/ui/kit/kit_tokens.dart        KitTokens.fallback sizes, radii, spacing + the static constants
  lib/ui/kit/kit_text.dart          KitText.styleFor: the ten type roles
  lib/ui/kit/kit_motion.dart        durations, springs, laps
  lib/ui/theme_roles.dart           every `const x = ThemeRoles(...)` pack (Graphite and the rest)
  lib/ui/kit/style/kit_style*.dart  the style schools' declared constants and sharp radii
and writes one Kotlin file of values (FlutterKit*.kt objects). Native token files read these values; nothing in them
is typed by hand. Every number in the output comes from Flutter.

Usage: gen_tokens.py --repo /path/to/oc_app [--ref mobile-next/master] --out path/to/FlutterKit.kt [--report out.md]
"""
import argparse, re, subprocess, sys
from fractions import Fraction

def show(repo, ref, path):
    return subprocess.run(["git", "-C", repo, "show", f"{ref}:{path}"], capture_output=True, text=True, check=True).stdout

def snake(name):
    s = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name.lstrip("_"))
    return s.upper()

def num(expr):
    """Evaluate a Dart numeric literal or a simple quotient/product (1 / 3.6, .5, 34 / 28)."""
    e = expr.strip().rstrip(",")
    if not re.fullmatch(r"[0-9.\s/*+\-()]+", e):
        return None
    try:
        return float(eval(e, {"__builtins__": {}}, {}))
    except Exception:
        return None

def kfloat(v):
    return f"{v!r}f" if v != int(v) else f"{int(v)}f"

def kconst(v):
    """`Int = 16` for whole numbers (so native const vals can use them), `Float = 0.38f` otherwise."""
    return f"Int = {int(v)}" if v == int(v) else f"Float = {v!r}f"

def block(src, start_pat):
    """The text of the first balanced (...) after start_pat."""
    m = re.search(start_pat, src)
    if not m:
        return None
    i = src.index("(", m.end() - 1)
    depth = 0
    for j in range(i, len(src)):
        if src[j] == "(":
            depth += 1
        elif src[j] == ")":
            depth -= 1
            if depth == 0:
                return src[i + 1 : j]
    return None

def strip_comments(s):
    s = re.sub(r"//[^\n]*", "", s)
    return re.sub(r"/\*.*?\*/", "", s, flags=re.S)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True)
    ap.add_argument("--ref", default="mobile-next/master")
    ap.add_argument("--out", required=True)
    ap.add_argument("--report")
    a = ap.parse_args()
    sha = subprocess.run(["git", "-C", a.repo, "rev-parse", "--short=9", a.ref], capture_output=True, text=True, check=True).stdout.strip()
    get = lambda p: strip_comments(show(a.repo, a.ref, p))

    out = []
    w = out.append
    w(f"// GENERATED by native/tool/design/gen_tokens.py from the Flutter kit at {a.ref} ({sha}). Do not edit by hand:")
    w("// change the Flutter source or the generator, then run it again. Every value here is Flutter's.")
    w("@file:Suppress(\"unused\", \"MagicNumber\")")
    w("")
    w("package io.github.eslamasabry.oc.ui.design.generated")
    w("")
    w("import io.github.eslamasabry.oc.ui.design.color.Roles")
    w("import io.github.eslamasabry.oc.ui.design.color.argb")
    w("import io.github.eslamasabry.oc.ui.design.type.TypeFamily")
    w("import io.github.eslamasabry.oc.ui.design.type.TypeSpec")
    w("")

    # 1. KitTokens: the fallback's numeric fields and the class's static constants.
    tokens = get("lib/ui/kit/kit_tokens.dart")
    fb_start = tokens.index("factory KitTokens.fallback")
    fb = block(tokens[fb_start:], r"return KitTokens\(")
    fields = {}
    for name, val in re.findall(r"\b([a-zA-Z]\w*)\s*:\s*([-0-9.][0-9.\s/*]*)\s*,", fb):
        v = num(val)
        if v is not None:
            fields[name] = v
    m = re.search(r"handleSize:\s*const Size\(\s*([0-9.]+)\s*,\s*([0-9.]+)\s*\)", fb)
    if m:
        fields["handleWidth"], fields["handleThickness"] = float(m.group(1)), float(m.group(2))
    statics = {}
    for name, val in re.findall(r"static const (?:double|int) (\w+)\s*=\s*([^;]+);", tokens):
        v = num(val)
        if v is not None:
            statics[name] = v
    w("/** `KitTokens.fallback` (lib/ui/kit/kit_tokens.dart): sizes, radii and spacing in logical pixels (dp). */")
    w("public object FlutterKitTokens {")
    for k in sorted(fields):
        w(f"    public const val {snake(k)}: {kconst(fields[k])}")
    w("")
    w("    // The class's static constants.")
    for k in sorted(statics):
        if k in fields:
            continue
        w(f"    public const val {snake(k)}: {kconst(statics[k])}")
    w("}")
    w("")

    # 2. Type: KitText.styleFor.
    text = get("lib/ui/kit/kit_text.dart")
    sf = text[text.index("static TextStyle styleFor(KitTextRole role)"):]
    sf = sf[: sf.index("};")]
    roles = {}
    for role, body in re.findall(r"KitTextRole\.(\w+)\s*=>\s*const TextStyle\((.*?)\)\s*,", sf, flags=re.S):
        size = num(re.search(r"fontSize:\s*([0-9.]+)", body).group(1))
        hm = re.search(r"height:\s*([0-9.]+)\s*/\s*([0-9.]+)", body)
        line = num(hm.group(1)) if hm else size
        wm = re.search(r"fontWeight:\s*FontWeight(?:\.w(\d+)|\((\d+)\))", body)
        weight = int(wm.group(1) or wm.group(2)) if wm else 400
        tm = re.search(r"letterSpacing:\s*(-?[0-9.]+)", body)
        track = float(tm.group(1)) if tm else 0.0
        mono = "AppMono" in body
        roles[role] = (int(size), int(line), weight, track, mono)
    w("/** `KitText.styleFor` (lib/ui/kit/kit_text.dart): size and line height in sp, weight, tracking in sp. */")
    w("public object FlutterKitType {")
    for role, (size, line, weight, track, mono) in roles.items():
        fam = ", TypeFamily.Mono" if mono else ""
        w(f"    public val {role[0].upper() + role[1:]}: TypeSpec = TypeSpec({size}, {line}, {weight}, {kfloat(track)}{fam})")
    w("}")
    w("")

    # 3. Motion.
    motion = get("lib/ui/kit/kit_motion.dart")
    w("/** `KitMotion` (lib/ui/kit/kit_motion.dart): durations in ms, springs (stiffness, damping per unit mass), laps. */")
    w("public object FlutterKitMotion {")
    durations = {}
    for name, ms in re.findall(r"static const (?:Duration )?(\w+)\s*=\s*Duration\(milliseconds:\s*(\d+)\)", motion):
        durations[name] = int(ms)
    for name, s in re.findall(r"static const (?:Duration )?(\w+)\s*=\s*Duration\(seconds:\s*(\d+)\)", motion):
        durations[name] = int(s) * 1000
    for k in sorted(durations):
        w(f"    public const val {snake(k)}_MS: Int = {durations[k]}")
    for name, body in re.findall(r"static const (\w+)\s*=\s*SpringDescription\((.*?)\);", motion, flags=re.S):
        st = re.search(r"stiffness:\s*([0-9.]+)", body); dp = re.search(r"damping:\s*([0-9.]+)", body); ms = re.search(r"mass:\s*([0-9.]+)", body)
        w(f"    public const val {snake(name)}_STIFFNESS: Float = {kfloat(float(st.group(1)))}")
        w(f"    public const val {snake(name)}_DAMPING: Float = {kfloat(float(dp.group(1)))}")
        w(f"    public const val {snake(name)}_MASS: Float = {kfloat(float(ms.group(1)) if ms else 1.0)}")
    for name, val in re.findall(r"static const double (\w+)\s*=\s*([^;]+);", motion):
        v = num(val)
        if v is not None:
            w(f"    public const val {snake(name)}: {kconst(v)}")
    w("}")
    w("")

    # 4. Colour roles: every pack in theme_roles.dart.
    tr = get("lib/ui/theme_roles.dart")
    native_fields = ["ground","surface1","surface2","surface3","hairline","text1","text2","text3","accent","onAccent","partner","onPartner","attention","attentionFill","onAttentionFill","attentionSurface","attentionLine","success","scrim","codeKeyword","codeString","codeType","elevationShadow"]
    w("/** Every `const x = ThemeRoles(...)` in lib/ui/theme_roles.dart, role for role. */")
    w("public object FlutterKitRoles {")
    packs = {}
    for name in re.findall(r"const (\w+)\s*=\s*ThemeRoles\(", tr):
        body = block(tr, rf"const {name}\s*=\s*ThemeRoles\(")
        vals = dict(re.findall(r"(\w+):\s*Color\((0x[0-9A-Fa-f]{8})\)", body))
        dark = "Brightness.dark" in body
        missing = [f for f in native_fields if f not in vals]
        if missing:
            w(f"    // {name}: skipped, Flutter does not set {', '.join(missing)}")
            continue
        packs[name] = vals
        args = ", ".join(f"{f} = argb({vals[f].upper().replace('0X','0x')})" for f in native_fields)
        w(f"    public val {name}: Roles = Roles(dark = {str(dark).lower()}, {args})")
    w("}")
    w("")

    # 5. Style schools: declared constants and sharp radii.
    w("/** The style schools (lib/ui/kit/style/kit_style_*.dart): their declared constants and Corners=Sharp radius. */")
    w("public object FlutterKitStyles {")
    style_vals = {}
    for school in ["solid", "soft", "brutal", "paper", "signal"]:
        src = get(f"lib/ui/kit/style/kit_style_{school}.dart")
        sr = re.search(r"sharpRadius:\s*([0-9.]+)", src)
        style_vals[f"{school}_sharp_radius"] = float(sr.group(1)) if sr else 2.0
        for name, val in re.findall(r"static const (?:double )?(\w+)\s*=\s*([-0-9.][^;]*);", src):
            v = num(val)
            if v is not None:
                style_vals[f"{school}_{name.lstrip('_')}"] = v
    for k in sorted(style_vals):
        w(f"    public const val {snake(k)}: {kconst(style_vals[k])}")
    w("}")

    open(a.out, "w").write("\n".join(out) + "\n")
    summary = f"tokens {len(fields)}+{len(statics)}, type roles {len(roles)}, durations {len(durations)}, packs {len(packs)}, style values {len(style_vals)}"
    print(summary)
    if a.report:
        open(a.report, "w").write(summary + "\n")

if __name__ == "__main__":
    main()
