"""Generate KitIcons.kt (Phosphor 2.1 paths as ImageVectors) from the Flutter AppIconography set."""
import re, sys, os
APP = sys.argv[1]; PF = sys.argv[2]; SVG = sys.argv[3]; OUT = sys.argv[4]
src = open(APP).read()
# static const name = IconData(0xe17e, fontFamily: 'AppPhosphorRegular', matchTextDirection: false,);
pat = re.compile(r"static const (\w+)\s*=\s*IconData\(\s*(0x[0-9a-fA-F]+),\s*fontFamily:\s*'(\w+)',\s*matchTextDirection:\s*(true|false)", re.S)
icons = pat.findall(src)
aliases = re.findall(r"static const (\w+)\s*=\s*AppIconography\.(\w+);", src)
def table(path, flat=True):
    t = {}
    s = open(path).read()
    if flat:
        for name, cp in re.findall(r"static const (\w+) = PhosphorFlatIconData\((0x[0-9a-f]+)", s): t[int(cp,16)] = name
    else:
        for name, cp in re.findall(r"static const (\w+) = PhosphorDuotoneIconData\(\s*(0x[0-9a-f]+)", s): t[int(cp,16)] = name
    return t
reg = table(f"{PF}/phosphor_icons_regular.dart"); fil = table(f"{PF}/phosphor_icons_fill.dart"); duo = table(f"{PF}/phosphor_icons_duotone.dart", False)
def kebab(n): return re.sub(r"(?<=[A-Z])([A-Z][a-z])", r"-\1", re.sub(r"(?<=[a-z0-9])([A-Z])", r"-\1", n)).replace("_","-").lower()
fam = {"AppPhosphorRegular": (reg, "regular", ""), "AppPhosphorFill": (fil, "fill", "-fill"), "AppPhosphorDuotone": (duo, "duotone", "-duotone")}
out = []; missing = []
for name, cp, family, mirror in icons:
    t, folder, suf = fam[family]
    pn = t.get(int(cp,16))
    if not pn:
        # duotone background lookup uses the regular-weight codepoint in the duotone font
        pn = duo.get(int(cp,16)+1) if family=="AppPhosphorDuotone" else None
    if not pn: missing.append((name,cp,family)); continue
    f = f"{SVG}/{folder}/{kebab(pn)}{suf}.svg"
    if not os.path.exists(f):
        # numbers: e.g. numberCircleOne -> number-circle-one ; try digits split
        alt = re.sub(r"([a-z])(\d)", r"\1-\2", kebab(pn)); f2 = f"{SVG}/{folder}/{alt}{suf}.svg"
        if os.path.exists(f2): f = f2
        else: missing.append((name,cp,family,pn)); continue
    paths = re.findall(r'<path d="([^"]+)"( opacity="([0-9.]+)")?', open(f).read())
    out.append((name, pn, folder, mirror=="true", [(d, float(o) if o else 1.0) for d,_,o in paths]))
names = {o[0] for o in out}
KW = {'package','in','is','as','object','fun','class','interface','typealias','val','var','when','try','throw','return','null','true','false','this','super','do','if','else','for','while','break','continue','typeof'}
def kt(n): return f'`{n}`' if n in KW else n
lines = ["// Generated by tools/gen_icons.py from the Flutter AppIconography set (lib/ui/app_iconography.dart,",
"// mobile-next/master 8302de537) and Phosphor 2.1 artwork (@phosphor-icons/core 2.1.1, MIT). Do not edit by hand.",
"package io.github.eslamasabry.oc.ui.kit.icon", "",
"import androidx.compose.ui.graphics.vector.ImageVector", "",
"/**", " * The app's one icon vocabulary (Dart `AppIconography` and `AppIcons`): Phosphor regular for actions, fill for a few",
" * states, duotone for selected navigation. Names match the Dart set so a port reads the same. Each glyph is built",
" * once, on first use. Direction glyphs (back, carets, reply, undo...) mirror in RTL.", " */",
"public object KitIcons {"]
for name, pn, folder, mirror, paths in out:
    arr = ", ".join(f'"{d}" to {o}f' for d,o in paths)
    lines.append(f'    /** Phosphor `{pn}` ({folder}). */')
    lines.append(f'    public val {kt(name)}: ImageVector by lazy {{ phosphor("{name}", {str(mirror).lower()}, {arr}) }}')
for a, target in aliases:
    if target in names and a not in names:
        lines.append(f'    /** The verb `{a}` (Dart `AppIcons.{a}`). */')
        lines.append(f'    public val {kt(a)}: ImageVector get() = {kt(target)}')
lines.append("}")
open(OUT,"w").write("\n".join(lines)+"\n")
print("icons", len(out), "missing", missing, file=sys.stderr)
